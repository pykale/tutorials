"""Emit ``_shared/metadata/tutorial.schema.json`` from the pydantic model.

The schema is generated, never hand-edited, so editors validating ``metadata.yml`` and
``validate_catalog.py`` can never drift apart. ``--check`` fails if the committed file is stale,
which is what CI runs.
"""

from __future__ import annotations

import argparse
import json
import sys

from models import SCHEMA_PATH, TutorialMetadata


def build_schema() -> str:
    schema = TutorialMetadata.model_json_schema()
    schema["$schema"] = "https://json-schema.org/draft/2020-12/schema"
    schema["$id"] = "https://pykale.github.io/tutorials/schemas/tutorial.schema.json"
    schema["title"] = "PyKale tutorial metadata"
    schema["description"] = "Generated by scripts/generate_schema.py -- do not edit by hand."
    return json.dumps(schema, indent=2, sort_keys=True) + "\n"


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="fail if the committed schema is stale")
    args = parser.parse_args()

    schema = build_schema()

    if args.check:
        if not SCHEMA_PATH.exists():
            print(f"missing {SCHEMA_PATH}; run: python scripts/generate_schema.py")
            return 1
        if SCHEMA_PATH.read_text(encoding="utf-8") != schema:
            print(f"{SCHEMA_PATH} is stale; run: python scripts/generate_schema.py")
            return 1
        print("schema up to date")
        return 0

    SCHEMA_PATH.parent.mkdir(parents=True, exist_ok=True)
    SCHEMA_PATH.write_text(schema, encoding="utf-8")
    print(f"wrote {SCHEMA_PATH}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
